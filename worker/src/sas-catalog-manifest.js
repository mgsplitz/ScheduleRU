// These ids are already referenced by reviewed, source-backed exclusion rules.
// Keeping them stable lets that policy continue to protect catalog-listed paths.
const CANONICAL_IDS = new Map([
  ["criminal-justice:major", "sasnb-criminal-justice-major"],
  ["health-and-society:minor", "sasnb-health-and-society-minor"],
]);

function displayName(label) {
  return label
    .replace(/(?:\s*\|\s*|\s+)(?:BA|BS)(?:\s+or\s+(?:BA|BS))?\s*$/i, "")
    .replace(/\s*\((?:Major|Minor)(?:\s*(?:,|\/)\s*(?:Major|Minor))*\)\s*/i, "")
    .replace(/\s+/g, " ")
    .trim();
}

function degreeType(label) {
  const match = label.match(/(?:\|\s*|\s+)((?:BA|BS)(?:\s+or\s+(?:BA|BS))?)\s*$/i);
  return match ? match[1].toUpperCase() : null;
}

function programTypes(label) {
  return [...new Set([...label.matchAll(/\b(Major|Minor)\b/gi)].map((match) => match[1].toLowerCase()))];
}

export const SAS_CATALOG_PROGRAMS = Object.freeze(SAS_CATALOG_ROWS.flatMap(([programSlug, label]) => {
  const name = displayName(label);
  const degree = degreeType(label);
  return programTypes(label).map((type) => Object.freeze({
    id: CANONICAL_IDS.get(`${programSlug}:${type}`) || `sasnb-catalog-${programSlug}-${type}`,
    name,
    school_slug: "sasnb",
    program_slug: programSlug,
    type,
    catalog_year: "Official SAS catalog list",
    academic_program_code: null,
    degree_type: degree,
    program_family_id: `sasnb-catalog-${programSlug}`,
    source_url: `https://sasundergrad.rutgers.edu/majors-and-core-curriculum/major/major-minor-details/${programSlug}`,
    review_status: "catalog_listed",
    coverage_status: "catalog_listed",
    requirements_available: false,
    requirements_notice: "Catalog-listed program: its program-specific requirements are still being reviewed. Use the official SAS catalog and advising to confirm degree progress.",
  }));
}));
